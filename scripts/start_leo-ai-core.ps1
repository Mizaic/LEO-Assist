# LEO-AI-CORE - Local Development Startup
# Creates / activates .venv, installs all deps, starts every microservice.
#
# Usage:
#   .\scripts\start_leo-ai-core.ps1                            # full stack — ALL services including inference + training worker
#   .\scripts\start_leo-ai-core.ps1 -SkipInstall               # skip pip/npm install
#   .\scripts\start_leo-ai-core.ps1 -NoWorkers                 # skip pipeline worker
#   .\scripts\start_leo-ai-core.ps1 -NoModelInference          # skip NER inference service
#   .\scripts\start_leo-ai-core.ps1 -NoTrainingWorker          # skip NER training worker
#   .\scripts\start_leo-ai-core.ps1 -Services api,ui           # named subset (others skipped)
#   .\scripts\start_leo-ai-core.ps1 -PipelineWorkers 3         # 3 pipeline workers (scale up for bulk runs)
#   .\scripts\start_leo-ai-core.ps1 -TermWorkers 3             # 3 terminology API instances (8001, 8011, 8021)
#
# -- Azure Container Apps (dev) parity ---------------------------------------
# Local -Services name      ACA app name           ACR image (ci-build.yml)
#   api                     core-api               core-api
#   terminology_api         terminology-api        terminology-api
#   fhir_api                fhir-api               fhir-api
#   analytics_api           analytics-api          analytics-api
#   model_inference         model-inference        model-inference
#   training_worker         training-worker        training-worker
#   pipeline_worker         pipeline-worker        pipeline-worker
#   ui                      ui                     ui
#
#   Coding and episode logic live in services/coding_worker and services/analysis_worker
#   Python packages (imported by pipeline-worker and tests). Standalone ACA images
#   for coding-worker / analysis-worker are deprecated.
#
# Model inference service:
#   Starts by default. Downloads the active NER model from Azure Blob at startup.
#   Exposes /extract, /health, /reload, /versions on -ModelInferencePort (default 8004).
#   Use -NoModelInference to skip if you only need LLM-based coding.
#
# Training worker:
#   Starts by default. Reads TrainingLabel nodes from Neo4j, trains NER head, uploads to blob.
#   Exposes /train/jobs, /train/progress/{job_id} on -TrainingWorkerPort (default 8005).
#   Use -NoTrainingWorker to skip if you are not doing model training today.
#
# Terminology API workers (-TermWorkers N):
#   Starts N independent uvicorn instances of the Terminology API on ports
#   $TermPort, $TermPort+10, $TermPort+20, ... (default: 8001, 8011, 8021, ...).
#   Each instance loads its own embedding model. TERMINOLOGY_API_URLS is set in
#   the environment so pipeline workers and evaluation scripts round-robin across all.
#   Recommended: 3 instances for evaluation runs, 1 for normal development.

param(
    [int]$ApiPort             = 8000,
    [int]$TermPort            = 8001,
    [int]$FhirPort            = 8002,
    [int]$AnalyticsPort       = 8003,
    [int]$ModelInferencePort  = 8004,
    [int]$TrainingWorkerPort  = 8005,
    [int]$PipelineWorkerPort  = 8006,
    [int]$UiPort              = 3000,
    [int]$PipelineWorkers     = 1,
    [int]$TermWorkers         = 1,
    [switch]$SkipInstall,
    [switch]$NoWorkers,
    [switch]$NoModelInference,
    [switch]$NoTrainingWorker,
    [string[]]$Services       = @()
)

$ErrorActionPreference = "Stop"

$RepoRoot               = Split-Path -Parent $PSScriptRoot
$VenvDir                = Join-Path $RepoRoot ".venv"
$VenvPython             = Join-Path $VenvDir  "Scripts\python.exe"
# Separate venv for the training worker — keeps cupy/torch/spacy-transformers
# out of the shared venv so other services don't load GPU libs unnecessarily.
$TrainingVenvDir        = Join-Path $RepoRoot ".venv-training"
$TrainingVenvPython     = Join-Path $TrainingVenvDir "Scripts\python.exe"
$UiDir                  = Join-Path $RepoRoot "services\ui"
$ApiDir                 = Join-Path $RepoRoot "services\api"
$ModelInferenceDir      = Join-Path $RepoRoot "services\model_inference"
$TrainingWorkerDir      = Join-Path $RepoRoot "services\training_worker"
$ReqFile                = Join-Path $RepoRoot "requirements.txt"
$ApiReq                 = Join-Path $ApiDir "requirements.txt"
$ModelInferenceReq      = Join-Path $ModelInferenceDir "requirements.txt"
$TrainingWorkerReq      = Join-Path $TrainingWorkerDir "requirements.txt"
$ModelCacheDir          = Join-Path $RepoRoot ".model_cache"

Write-Host ""
Write-Host "  LEO-AI-CORE - Local Dev Startup" -ForegroundColor Cyan
Write-Host ""

# -- Environment / secrets -------------------------------------------------
# Load order (later overrides earlier):
#   1. secrets\.env          -- legacy full .env (still supported, git-ignored)
#   2. secrets\.env.secrets  -- generated by sync-secrets-local.ps1 from KV
#   3. secrets\.env.config   -- non-secret config + AZURE_KEYVAULT_URL (committed)
#
# .env.config is loaded LAST so it always wins for AZURE_KEYVAULT_URL and
# other authoritative config, overriding stale user-level env vars.
function Import-DotEnv {
    param([string]$Path, [switch]$Override)
    if (-not (Test-Path $Path)) { return 0 }
    $count = 0
    Get-Content $Path | ForEach-Object {
        $line = $_.Trim()
        if (-not $line -or $line.StartsWith('#')) { return }
        $eqIdx = $line.IndexOf('=')
        if ($eqIdx -lt 1) { return }
        $key = $line.Substring(0, $eqIdx).Trim()
        $val = $line.Substring($eqIdx + 1)
        if ($val -match '^(.*?)\s{2,}#') { $val = $Matches[1] }
        $val = $val.Trim()
        if ($Override -or -not [System.Environment]::GetEnvironmentVariable($key, 'Process')) {
            [System.Environment]::SetEnvironmentVariable($key, $val, 'Process')
            $count++
        }
    }
    return $count
}

# 1. Legacy secrets file (low priority - only sets vars not already present)
$n = Import-DotEnv (Join-Path $RepoRoot "secrets\.env")
if ($n -gt 0) { Write-Host "  [env]  Loaded $n vars from secrets\.env" -ForegroundColor DarkGray }

# 2. KV-generated secrets file (mid priority)
$n = Import-DotEnv (Join-Path $RepoRoot "secrets\.env.secrets")
if ($n -gt 0) { Write-Host "  [env]  Loaded $n vars from secrets\.env.secrets" -ForegroundColor DarkGray }

# 3. Non-secret config (highest priority -- always overrides, fixes AZURE_KEYVAULT_URL etc.)
$configFile = Join-Path $RepoRoot "secrets\.env.config"
$n = Import-DotEnv $configFile -Override
if ($n -gt 0) {
    Write-Host "  [env]  Applied $n config vars from secrets\.env.config (override)" -ForegroundColor Green
} else {
    Write-Host "  [env]  secrets\.env.config not found - using system env vars only." -ForegroundColor Yellow
}

# Confirm the vault URL that child processes will use
$kvUrl = [System.Environment]::GetEnvironmentVariable("AZURE_KEYVAULT_URL", 'Process')
if ($kvUrl) {
    Write-Host "  [kv]   Key Vault: $kvUrl" -ForegroundColor Green
} else {
    Write-Host "  [kv]   AZURE_KEYVAULT_URL not set - KV secret loading disabled." -ForegroundColor Yellow
}

# Model registry: use Neo4j by default. Set MODEL_REGISTRY_STORE=json for file-based.
if (-not [System.Environment]::GetEnvironmentVariable("MODEL_REGISTRY_STORE", 'Process')) {
    [System.Environment]::SetEnvironmentVariable("MODEL_REGISTRY_STORE", "neo4j", 'Process')
}
# Fallback path when MODEL_REGISTRY_STORE=json
$absRegistryPath = Join-Path $ModelCacheDir "model_registry.json"
[System.Environment]::SetEnvironmentVariable("MODEL_REGISTRY_STORE_PATH", $absRegistryPath, 'Process')

# -- Local model cache directory -------------------------------------------
# Model inference service downloads NER artifacts from Azure Blob into this dir.
# Committed to .gitignore; safe to delete between dev sessions.
if (-not (Test-Path $ModelCacheDir)) {
    New-Item -ItemType Directory -Path $ModelCacheDir | Out-Null
    Write-Host "  [dir]  Created .model_cache/ for NER model artifacts." -ForegroundColor Green
}

# -- Python virtual environment (shared — no GPU/cupy deps) ----------------
if (-not (Test-Path $VenvPython)) {
    Write-Host "  [venv] Creating shared virtual environment (.venv)..." -ForegroundColor Yellow
    python -m venv $VenvDir
    Write-Host "  [venv] .venv created." -ForegroundColor Green
}

# -- Training worker virtual environment (isolated — cupy + torch + spacy-transformers) --
if (-not $NoTrainingWorker) {
    if (-not (Test-Path $TrainingVenvPython)) {
        Write-Host "  [venv] Creating training worker virtual environment (.venv-training)..." -ForegroundColor Yellow
        python -m venv $TrainingVenvDir
        Write-Host "  [venv] .venv-training created." -ForegroundColor Green
    }
}

# -- Python dependencies ---------------------------------------------------
if (-not $SkipInstall) {
    Write-Host "  [pip]  Installing / upgrading shared Python dependencies..." -ForegroundColor Yellow
    & $VenvPython -m pip install --quiet --upgrade pip
    & $VenvPython -m pip install --quiet --upgrade -r $ReqFile
    # Core API has its own requirements (slowapi, azure-identity, etc.)
    if (Test-Path $ApiReq) {
        & $VenvPython -m pip install --quiet --upgrade -r $ApiReq
    }
    # Model inference service has its own requirements (spaCy, azure-storage-blob)
    # that may drift from the monorepo floor - install on top of the venv.
    if (Test-Path $ModelInferenceReq) {
        & $VenvPython -m pip install --quiet --upgrade -r $ModelInferenceReq
    }
    Write-Host "  [pip]  Shared Python dependencies up to date." -ForegroundColor Green

    # Training worker installs into its own venv to keep GPU libs isolated.
    if (-not $NoTrainingWorker -and (Test-Path $TrainingWorkerReq)) {
        Write-Host "  [pip]  Installing training worker dependencies (.venv-training)..." -ForegroundColor Yellow
        & $TrainingVenvPython -m pip install --quiet --upgrade pip
        & $TrainingVenvPython -m pip install --quiet --upgrade -r $TrainingWorkerReq
        Write-Host "  [pip]  Training worker dependencies up to date." -ForegroundColor Green
    }
}

# -- Node dependencies -----------------------------------------------------
if (-not $SkipInstall) {
    Write-Host "  [npm]  Installing / updating UI dependencies..." -ForegroundColor Yellow
    Push-Location $UiDir
    npm.cmd install --silent
    Pop-Location
    Write-Host "  [npm]  UI dependencies up to date." -ForegroundColor Green
} elseif (-not (Test-Path (Join-Path $UiDir "node_modules"))) {
    Write-Host "  [npm]  node_modules missing - running npm install..." -ForegroundColor Yellow
    Push-Location $UiDir
    npm.cmd install --silent
    Pop-Location
    Write-Host "  [npm]  UI dependencies installed." -ForegroundColor Green
}

# -- Helpers ---------------------------------------------------------------

function ShouldStart([string]$Name) {
    if ($Services.Count -eq 0) { return $true }
    return $Services -contains $Name
}

function Start-ServiceWindow {
    param(
        [string]$Title,
        [string]$Command,
        [string]$WorkDir = $RepoRoot
    )
    $preamble = "Set-Location -LiteralPath '$WorkDir'; `$env:PYTHONPATH = '$RepoRoot'"
    $titleCmd = "`$Host.UI.RawUI.WindowTitle = '$Title'"
    $fullCmd  = "$titleCmd; $preamble; $Command"
    Start-Process -FilePath "powershell" -ArgumentList "-NoExit", "-Command", $fullCmd -WorkingDirectory $WorkDir | Out-Null
}

# -- Start services --------------------------------------------------------
$windowCount = 0

Write-Host ""
Write-Host "  Starting services..." -ForegroundColor Green

# 1  Core API  (services/api)  ->  :8000
if (ShouldStart "api") {
    Start-ServiceWindow -Title "Core API :$ApiPort" -Command "& '$VenvPython' -m uvicorn app.main:app --app-dir '$ApiDir' --reload --reload-dir services/api --reload-dir libs --host 0.0.0.0 --port $ApiPort"
    Write-Host "    Core API           http://localhost:$ApiPort" -ForegroundColor White
    $windowCount++
}

# 2  Terminology API  (services/terminology_api)  ->  :8001 (+ optional extra instances)
#    Extra instances start on $TermPort+10, $TermPort+20, ... (e.g. 8011, 8021)
#    TERMINOLOGY_API_URLS is exported so coding workers and evaluation scripts
#    round-robin across all instances automatically.
if (ShouldStart "terminology_api") {
    $termPorts  = @()
    $termUrls   = @()
    for ($t = 0; $t -lt $TermWorkers; $t++) {
        $tPort = $TermPort + ($t * 10)
        $termPorts += $tPort
        $termUrls  += "http://localhost:$tPort"
        # Primary instance gets --reload (scoped to service dirs only).
        # All instances get --workers 4 so concurrent requests don't queue at the TCP layer.
        # Note: --reload and --workers are mutually exclusive in uvicorn, so the primary
        # uses reload (dev convenience) while workers use multi-process for throughput.
        if ($t -eq 0) {
            $termCmd = "& '$VenvPython' -m uvicorn services.terminology_api.app.main:app --reload --reload-dir services/terminology_api --reload-dir libs --host 0.0.0.0 --port $tPort"
        } else {
            $termCmd = "& '$VenvPython' -m uvicorn services.terminology_api.app.main:app --workers 4 --host 0.0.0.0 --port $tPort"
        }
        Start-ServiceWindow -Title "Terminology API :$tPort" -Command $termCmd
        Write-Host "    Terminology API    http://localhost:$tPort$(if ($t -eq 0) { ' (primary)' } else { " (worker $t)" })" -ForegroundColor White
        $windowCount++
    }

    # Export TERMINOLOGY_API_URLS so child processes (coding workers, eval scripts) inherit it
    $termUrlsJoined = $termUrls -join ","
    [System.Environment]::SetEnvironmentVariable("TERMINOLOGY_API_URLS", $termUrlsJoined, "Process")
    if ($TermWorkers -gt 1) {
        Write-Host "    TERMINOLOGY_API_URLS=$termUrlsJoined" -ForegroundColor DarkGray
    }
}

# 3  FHIR API  (services/fhir_api)  ->  :8002
if (ShouldStart "fhir_api") {
    Start-ServiceWindow -Title "FHIR API :$FhirPort" -Command "& '$VenvPython' -m uvicorn services.fhir_api.app.main:app --reload --reload-dir services/fhir_api --reload-dir libs --host 0.0.0.0 --port $FhirPort"
    Write-Host "    FHIR API           http://localhost:$FhirPort" -ForegroundColor White
    $windowCount++
}

# 4  Analytics API  (services/analytics_api)  ->  :8003
if (ShouldStart "analytics_api") {
    Start-ServiceWindow -Title "Analytics API :$AnalyticsPort" -Command "& '$VenvPython' -m uvicorn services.analytics_api.app.main:app --reload --reload-dir services/analytics_api --reload-dir libs --host 0.0.0.0 --port $AnalyticsPort"
    Write-Host "    Analytics API      http://localhost:$AnalyticsPort" -ForegroundColor White
    $windowCount++
}

# 5  Model Inference Service  (NER spaCy endpoint)
#    Downloads the active model from Azure Blob at startup. Hot-reload via /reload.
#    On by default; suppress with -NoModelInference or -Services (without model_inference).
if (-not $NoModelInference -and (ShouldStart "model_inference")) {
    $miCmd = "& '$VenvPython' -m uvicorn app.main:app --app-dir '$ModelInferenceDir' --host 0.0.0.0 --port $ModelInferencePort"
    Start-ServiceWindow -Title "Model Inference :$ModelInferencePort" -Command $miCmd -WorkDir $RepoRoot
    Write-Host "    Model Inference    http://localhost:$ModelInferencePort  (NER /extract /health /reload /versions)" -ForegroundColor White
    $windowCount++
} else {
    Write-Host "    Model Inference    [skipped; use without -NoModelInference to start]" -ForegroundColor DarkGray
}

# 6  Training Worker  (NER fine-tuning)
#    On by default; suppress with -NoTrainingWorker or -Services (without training_worker).
#    Kills any existing process on the port before starting.
if (-not $NoTrainingWorker -and (ShouldStart "training_worker")) {
    $existing = Get-NetTCPConnection -LocalPort $TrainingWorkerPort -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($existing) {
        $procId = $existing.OwningProcess
        Stop-Process -Id $procId -Force -ErrorAction SilentlyContinue
        Write-Host "    Training Worker    [killed existing PID $procId]" -ForegroundColor Yellow
        Start-Sleep -Seconds 2
    }
    $twCmd = "& '$TrainingVenvPython' -m uvicorn app.main:app --app-dir '$TrainingWorkerDir' --host 0.0.0.0 --port $TrainingWorkerPort"
    Start-ServiceWindow -Title "Training Worker :$TrainingWorkerPort" -Command $twCmd -WorkDir $RepoRoot
    Write-Host "    Training Worker    http://localhost:$TrainingWorkerPort  (NER fine-tuning /train/jobs /train/progress)" -ForegroundColor White
    $windowCount++
} else {
    Write-Host "    Training Worker    [skipped; use without -NoTrainingWorker to start]" -ForegroundColor DarkGray
}

# 6  Pipeline Worker  (dual-mode: message bus consumer + HTTP SSE on :$PipelineWorkerPort)
#    The first worker runs uvicorn so /test-run/batch SSE is reachable by the UI.
#    Additional workers (PipelineWorkers > 1) run on sequential ports for scale.
if (-not $NoWorkers -and (ShouldStart "pipeline_worker")) {
    for ($i = 1; $i -le $PipelineWorkers; $i++) {
        $workerPort = $PipelineWorkerPort + ($i - 1)
        # Set port env var inline then launch uvicorn. The dual-mode FastAPI app
        # runs the message bus consumer as a background lifespan task alongside
        # the HTTP server, so /test-run/batch SSE is served here, not on the Core API.
        Start-ServiceWindow -Title "Pipeline Worker $i :$workerPort" `
            -Command "`$env:PIPELINE_WORKER_PORT='$workerPort'; & '$VenvPython' -m uvicorn services.pipeline_worker.app.main:app --host 0.0.0.0 --port $workerPort --log-level info"
    }
    Write-Host "    Pipeline Workers   (x$PipelineWorkers - HTTP :$PipelineWorkerPort + message bus)" -ForegroundColor White
    $windowCount += $PipelineWorkers
}

# 8  UI  (Next.js)  ->  :3000
if (ShouldStart "ui") {
    Start-ServiceWindow -Title "UI :$UiPort" -Command "npm.cmd run dev -- --port $UiPort" -WorkDir $UiDir
    Write-Host "    UI                 http://localhost:$UiPort" -ForegroundColor White
    $windowCount++
}

# -- Summary ---------------------------------------------------------------
Write-Host ""
Write-Host "  $windowCount PowerShell window(s) opened. Close them to stop services." -ForegroundColor DarkGray
if ($TermWorkers -gt 1) {
    Write-Host "  Terminology API running on $TermWorkers instances. TERMINOLOGY_API_URLS is set for round-robin." -ForegroundColor Cyan
    Write-Host "  To run the evaluation script against all instances:" -ForegroundColor DarkGray
    Write-Host "    .venv\Scripts\python.exe -m scripts.evaluate_training_data" -ForegroundColor DarkGray
}
Write-Host ""
