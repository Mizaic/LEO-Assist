"""Hard-cut script for the episode-first rebuild.

Atlas trace:
  DI: DI-8A5FCF4F (Defence-in-depth episode detector)

Performs the Phase 6 deletion of the v1 episode + SBAR system. Hard
gate: refuses to run unless a recent compliance/episode-v2-shadow-
report.json shows BOTH zero net regression on auto-publishable
cases AND >= the configured recall floor on the labelled regression
cohort. This script is intentionally idempotent: it can be re-run
safely in dry-run mode at any time to print the planned deletions.

Steps performed when --execute is set:

  1. Verify the shadow report exists, is fresh enough, and meets the
     promotion thresholds.
  2. Flip the episode_pipeline feature flag default from "v1" -> "v2"
     by editing libs/feature_flags.py.
  3. Delete the v1 modules (episode_builder, episode_engine, the
     legacy patient-level SBAR orchestrator, the legacy episode
     subgraphs, and the legacy regression cohort scripts).
  4. Mark the listed Atlas DOs and DIs Obsolete via the Atlas MCP
     server -- this script prints the dcId list and the rationale
     so the QA / RA lead can perform the API calls; it does NOT
     touch Atlas directly to keep the script reversible.
  5. Print a summary that the operator commits.

Until the shadow window has produced an acceptable
compliance/episode-v2-shadow-report.json, the script is dry-run
only and prints the planned deletions plus the gating verdict.
"""

