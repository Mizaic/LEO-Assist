def _referral_route_from_concept(concept_name: str) -> str:
    """Map a referral concept name to the NCDA referral_route value."""
    name = concept_name.lower()
    if any(
        k in name
        for k in ("fast track", "fast-track", "2ww", "two week", "urgent suspected")
    ):
        return "two_week_wait"
    if any(k in name for k in ("emergency", "a&e", "accident", "ae ", "a & e")):
        return "emergency"
    if any(k in name for k in ("routine", "elective", "non-urgent")):
        return "routine"
    return "other"


def _extract_condition_key(concept_name: str) -> str:
    """Map a SNOMED concept name to a canonical cancer-site key.

    DI-LEO-AI-200: NSS classification rule. Only return
    'non_site_specific' when the concept name explicitly matches an
    NSS surface form (see _NSS_PHRASE_RE) -- "non-site-specific
    symptoms", "2WW NSS", "NSS referral", "fast track NSS", or the
    full "Fast track referral for suspected cancer due to non-site-
    specific symptoms" phrase. The explicit SNOMED concept ID
    (1556551000000104) is handled in _SITE_BY_CONCEPT_ID.

    Generic cancer terms ("carcinoma", "neoplasm", "cancer", etc.)
    that lack any site signal now return 'unknown' so the episode
    builder can absorb them into a temporally-overlapping typed
    pathway, instead of opening a phantom NSS pathway that the
    duplicate resolver would later merge away.
    """
    name = concept_name.lower()
    if _NSS_PHRASE_RE.search(name):
        return "non_site_specific"
    for keyword, key in _SITE_MAP:
        if keyword in name:
            return key
    if any(term in name for term in _GENERIC_CANCER_TERMS):
        return "unknown"
    return "unknown"


def _extract_condition_key_from_anchor(anchor: dict[str, Any]) -> str:
    """Resolve site key from anchor.

    Resolution order:
    0a. site_source in {"explicit_2ww_code", "explicit_malignancy_code"}
        -- DI-LEO-AI-159. The encounter text contained an unambiguous
        Read/CTV3 code that fixes the cancer site (e.g. "(XaMeC)" =>
        breast 2WW referral, "(X78WM)" => malignant tumour of breast).
        This trumps every other source, including coded SNOMED, because
        the surface-form heuristic and SNOMED concept name can disagree
        with what the GP actually filed (e.g. lung clinic letter inside
        a breast 2WW workflow).
    0b. Explicit anchor['site_key'] -- set by text-path anchor detector
        from the gold-mined cancer_site_terms dictionary (DI-LEO-AI-155).
        This is preferred because the text-path generic sentinel
        concept_ids (e.g. "Text: confirmed cancer diagnosis") carry no
        site information.
    1. _SITE_BY_CONCEPT_ID -- explicit coded-base concept overrides.
    2. _DESCENDANT_SITE_MAP -- IS_A-expanded SNOMED descendants.
    3. _extract_condition_key -- keyword matching on concept_name.
    """
    site_source = str(anchor.get("site_source") or "").strip()
    explicit = str(anchor.get("site_key") or "").strip()
    if site_source in {"explicit_2ww_code", "explicit_malignancy_code"} and explicit:
        return explicit
    if explicit and explicit not in ("unknown", "non_site_specific"):
        return explicit
    concept_id = str(anchor.get("concept_id") or "").strip()
    if concept_id and concept_id in _SITE_BY_CONCEPT_ID:
        return _SITE_BY_CONCEPT_ID[concept_id]
    if concept_id and concept_id in _DESCENDANT_SITE_MAP:
        return _DESCENDANT_SITE_MAP[concept_id]
    fallback = _extract_condition_key(str(anchor.get("concept_name") or ""))
    if fallback in ("unknown", "non_site_specific") and explicit:
        return explicit
    return fallback


def _site_keys_compatible(episode_key: str, visit_key: str) -> bool:
    """Return True when a specialist visit site key is compatible with an episode."""
    if episode_key == visit_key:
        return True
    if visit_key == "unknown" or episode_key == "unknown":
        return True
    if visit_key in _PATHWAY_TO_SPECIFIC:
        if episode_key in _PATHWAY_TO_SPECIFIC[visit_key]:
            return True
    if episode_key in _PATHWAY_TO_SPECIFIC:
        if visit_key in _PATHWAY_TO_SPECIFIC[episode_key]:
            return True
    for specifics in _PATHWAY_TO_SPECIFIC.values():
        if episode_key in specifics and visit_key in specifics:
            return True
    return False
