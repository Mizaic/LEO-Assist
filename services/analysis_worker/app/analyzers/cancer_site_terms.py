# Pre-compiled per-site regexes for fast site detection.
_CANCER_SITE_REGEXES: dict[str, re.Pattern[str]] = {
    key: re.compile(
        r'\b(?:' + '|'.join(re.escape(f) for f in forms) + r')\b',
        re.IGNORECASE,
    )
    for key, forms in CANCER_SITE_TERMS.items()
    if forms
}

def match_cancer_site(text: str) -> tuple[str, int] | None:
    """Return (site_key, hit_count) for the site with the most matches."""
    if not text:
        return None
    best: tuple[str, int] | None = None
    for key, rx in _CANCER_SITE_REGEXES.items():
        n = len(rx.findall(text))
        if n > 0 and (best is None or n > best[1]):
            best = (key, n)
    return best
