/**
 * exportAuditReportPdf
 *
 * Captures a rendered audit report (the on-screen tiles, charts and tables)
 * and writes it to a paginated, branded A4 PDF. Every page carries a navy
 * header (LEO logo, report title, version, date, organisation) and a footer
 * with a page count and an information-governance notice.
 *
 * The report DOM is rasterised with html2canvas, then sliced across A4 pages
 * so a tall report exports cleanly without overflowing a single page.
 *
 * Atlas trace:
 *   DO: DO-AUDIT-PDF
 *   DI: DI-AUDIT-EXPORT
 *   Look up via: get_design_control(dc_type="design-output", dc_id="DO-AUDIT-PDF")
 */
import jsPDF from "jspdf";
import html2canvas from "html2canvas";

const PRIMARY = "#1F3A8A";
const WHITE = "#FFFFFF";
const GREY_TEXT = "#596577";

const PAGE_W = 210; // A4 portrait, mm
const PAGE_H = 297;
const MARGIN = 10;
const HEADER_H = 16;
const FOOTER_H = 10;
const CONTENT_TOP = HEADER_H + 4;
const CONTENT_BOTTOM = PAGE_H - FOOTER_H - 2;

export interface AuditReportPdfMeta {
  title: string;
  version: number;
  status: string;
  orgName?: string;
}

function drawLogo(doc: jsPDF, x: number, y: number, r: number) {
  doc.setFillColor(PRIMARY);
  doc.circle(x, y, r, "F");
  doc.setTextColor(WHITE);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(r * 3.2);
  doc.text("LEO", x, y + r * 1.1, { align: "center", baseline: "bottom" });
}

function drawHeader(doc: jsPDF, meta: AuditReportPdfMeta, generatedAt: string) {
  doc.setFillColor(PRIMARY);
  doc.rect(0, 0, PAGE_W, HEADER_H, "F");
  drawLogo(doc, MARGIN - 1, HEADER_H / 2, 4.5);

  doc.setTextColor(WHITE);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(meta.title, MARGIN + 8, HEADER_H / 2 - 1, { baseline: "middle" });

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text(`v${meta.version} - ${meta.status}`, MARGIN + 8, HEADER_H / 2 + 3.5, {
    baseline: "middle",
  });

  const rightX = PAGE_W - MARGIN;
  doc.setFontSize(7.5);
  doc.text(`Generated: ${generatedAt}`, rightX, HEADER_H / 2 - 1.5, {
    align: "right",
    baseline: "middle",
  });
  if (meta.orgName) {
    doc.text(`Organisation: ${meta.orgName}`, rightX, HEADER_H / 2 + 3, {
      align: "right",
      baseline: "middle",
    });
  }
}

function drawFooter(doc: jsPDF, pageNum: number, pageCount: number) {
  doc.setDrawColor("#E2E8F0");
  doc.setLineWidth(0.2);
  doc.line(MARGIN, PAGE_H - FOOTER_H, PAGE_W - MARGIN, PAGE_H - FOOTER_H);

  doc.setTextColor(GREY_TEXT);
  doc.setFont("helvetica", "italic");
  doc.setFontSize(7);
  doc.text(
    "Generated by LEO by Mizaic  -  Handle in line with your organisation's information governance policy",
    PAGE_W / 2,
    PAGE_H - FOOTER_H + 4,
    { align: "center", baseline: "middle" },
  );
  doc.setFont("helvetica", "normal");
  doc.text(`Page ${pageNum} of ${pageCount}`, PAGE_W - MARGIN, PAGE_H - FOOTER_H + 4, {
    align: "right",
    baseline: "middle",
  });
}

function sliceToPage(source: HTMLCanvasElement, topPx: number, heightPx: number): string {
  const slice = document.createElement("canvas");
  slice.width = source.width;
  slice.height = heightPx;
  const ctx = slice.getContext("2d");
  if (ctx) {
    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, slice.width, slice.height);
    ctx.drawImage(source, 0, topPx, source.width, heightPx, 0, 0, source.width, heightPx);
  }
  return slice.toDataURL("image/png");
}

function slugify(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "") || "report";
}

export async function exportAuditReportPdf(
  element: HTMLElement,
  meta: AuditReportPdfMeta,
): Promise<void> {
  const canvas = await html2canvas(element, {
    scale: 2,
    backgroundColor: "#ffffff",
    useCORS: true,
    logging: false,
    windowWidth: element.scrollWidth,
  });

  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  doc.setProperties({
    title: meta.title,
    subject: "LEO clinical audit report",
    author: meta.orgName || "LEO by Mizaic",
    creator: "LEO by Mizaic",
  });

  const generatedAt = new Date().toLocaleString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });

  const contentWmm = PAGE_W - MARGIN * 2;
  const usableHmm = CONTENT_BOTTOM - CONTENT_TOP;
  const pxPerMm = canvas.width / contentWmm;
  const pageHpx = Math.floor(usableHmm * pxPerMm);
  const totalPages = Math.max(1, Math.ceil(canvas.height / pageHpx));

  for (let page = 0; page < totalPages; page += 1) {
    if (page > 0) doc.addPage();
    const topPx = page * pageHpx;
    const sliceHpx = Math.min(pageHpx, canvas.height - topPx);
    const sliceData = sliceToPage(canvas, topPx, sliceHpx);
    const sliceHmm = sliceHpx / pxPerMm;
    drawHeader(doc, meta, generatedAt);
    drawFooter(doc, page + 1, totalPages);
    doc.addImage(sliceData, "PNG", MARGIN, CONTENT_TOP, contentWmm, sliceHmm);
  }

  const dateSlug = new Date().toISOString().slice(0, 10);
  doc.save(`${slugify(meta.title)}-v${meta.version}-${dateSlug}.pdf`);
}
