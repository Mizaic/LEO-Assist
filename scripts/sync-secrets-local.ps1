# -- LEO AI Core - Local Secret Sync from Key Vault -----------------------
# Pulls every secret from mizaicai-{env}-kv and writes them to
# secrets/.env.secrets (git-ignored). After running this once you can
# delete secrets/.env and use secrets/.env.config + secrets/.env.secrets
# for local development instead.
#
# Usage (first time and whenever secrets rotate):
#   .\scripts\sync-secrets-local.ps1 -Environment dev
#   .\scripts\sync-secrets-local.ps1 -Environment dev -VaultName kv-atlas-dev-4697
#   .\scripts\sync-secrets-local.ps1 -Environment dev -OutFile secrets\.env.secrets
#
# Requirements: az CLI logged in, Key Vault Secrets User role on the vault.
param(
    [Parameter(Mandatory)]
    [ValidateSet('dev', 'val', 'prod')]
    [string]$Environment,

    [string]$VaultName = '',
    [string]$OutFile = 'secrets\.env.secrets'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$KvName = if ($VaultName) { $VaultName } else { "mizaicai-$Environment-kv" }
Write-Host "  Pulling from vault: $KvName"

# KV secret name -> env var name
$SecretMap = [ordered]@{
    'neo4j-patient-uri'                   = 'NEO4J_URI'
    'neo4j-patient-password'              = 'NEO4J_PASSWORD'
    'neo4j-knowledge-uri'                 = 'KNOWLEDGE_GRAPH_NEO4J_URI'
    'neo4j-knowledge-password'            = 'KNOWLEDGE_GRAPH_NEO4J_PASSWORD'
    'neo4j-guideline-uri'                 = 'GUIDELINE_NEO4J_URI'
    'neo4j-guideline-password'            = 'GUIDELINE_NEO4J_PASSWORD'
    'redis-url'                           = 'REDIS_URL'
    'azure-ad-client-id'                  = 'AZURE_AD_CLIENT_ID'
    'azure-ad-client-secret'              = 'AZURE_AD_CLIENT_SECRET'
    'azure-ad-tenant-id'                  = 'AZURE_AD_TENANT_ID'
    'mail-graph-tenant-id'                = 'MAIL_GRAPH_TENANT_ID'
    'mail-graph-client-id'                = 'MAIL_GRAPH_CLIENT_ID'
    'mail-graph-client-secret'            = 'MAIL_GRAPH_CLIENT_SECRET'
    'azure-openai-api-key'                = 'AZURE_OPENAI_API_KEY'
    'azure-openai-endpoint'               = 'AZURE_OPENAI_ENDPOINT'
    'azure-service-bus-connection-string' = 'AZURE_SERVICE_BUS_CONNECTION_STRING'
    'aws-access-key-id'                   = 'AWS_ACCESS_KEY_ID'
    'aws-secret-access-key'               = 'AWS_SECRET_ACCESS_KEY'
    'aws-big-model'                       = 'AWS_BIG_MODEL'
    'aws-small-model'                     = 'AWS_SMALL_MODEL'
    'aws-max-model'                       = 'AWS_MAX_MODEL'
    'snomed-api-key'                      = 'SNOMED_API_KEY'
    'umls-api-key'                        = 'UMLS_API_KEY'
    'nhs-trud-api-key'                    = 'NHS_TRUD_API_KEY'
    'analytics-api-app-id'                = 'ANALYTICS_API_APP_ID'
    'fhir-api-app-id'                     = 'FHIR_API_APP_ID'
    'model-inference-app-id'              = 'MODEL_INFERENCE_APP_ID'
    'terminology-api-app-id'              = 'TERMINOLOGY_API_APP_ID'
    'auth-secret'                         = 'AUTH_SECRET'
    'service-auth-secret'                 = 'SERVICE_AUTH_SECRET'
    'nice-api-key'                        = 'NICE_API_KEY'
    'sdk-host-shared-secret'              = 'SDK_HOST_SHARED_SECRET'
    'sdk-widget-token-secret'             = 'SDK_WIDGET_TOKEN_SECRET'
    'azure-storage-connection-string'     = 'AZURE_STORAGE_CONNECTION_STRING'
}

$lines = @()
$lines += "# !! DO NOT COMMIT -- generated by sync-secrets-local.ps1 from $KvName !!"
$lines += "# Run: .\scripts\sync-secrets-local.ps1 -Environment dev  to refresh."
$lines += ""

$ok = 0; $err = 0

foreach ($kvName2 in $SecretMap.Keys) {
    $envVar = $SecretMap[$kvName2]
    try {
        $val = az keyvault secret show `
            --vault-name $KvName `
            --name $kvName2 `
            --query value `
            --output tsv 2>$null
        if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($val)) {
            Write-Warning "  SKIP  $kvName2 (not found or empty)"
            $lines += "# $envVar=  # not found in $KvName"
        } else {
            $lines += "$envVar=$val"
            Write-Host "  OK    $kvName2 -> $envVar"
            $ok++
        }
    } catch {
        Write-Warning "  ERROR $kvName2 : $_"
        $lines += "# $envVar=  # error fetching from KV"
        $err++
    }
}

$dir = Split-Path $OutFile -Parent
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
$lines | Set-Content $OutFile -Encoding UTF8

Write-Host ""
Write-Host "Written $ok secrets to $OutFile ($err errors)."
Write-Host "Next step: set AZURE_KEYVAULT_URL=https://$KvName.vault.azure.net in"
Write-Host "secrets\.env.config, then you can delete secrets\.env."
