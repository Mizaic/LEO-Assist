import jsPDF from "jspdf";
import html2canvas from "html2canvas";
import {
  buildSbarPdfCaptureRoot,
  SBAR_PDF_ADVISORY,
} from "@/lib/sbarPdfMarkup";
import {
  collectPdfBlocks,
  planPdfPageSlices,
  type PdfPageSlice,
} from "@/lib/sbarPdfPagination";

export { SBAR_PDF_ADVISORY };
export { markdownBodyToHtml } from "@/lib/sbarPdfMarkup";
export { planPdfPageSlices } from "@/lib/sbarPdfPagination";

export const SBAR_PDF_IG_FOOTER =
  "Generated by LEO by Mizaic - Handle in line with your organisation's " +
  "information governance policy";

const PRIMARY = "#1F3A8A";
const WHITE = "#FFFFFF";
const GREY_TEXT = "#596577";

const PAGE_W = 210;
const PAGE_H = 297;
const MARGIN = 10;
const HEADER_H = 14;
const FOOTER_H = 10;
const CONTENT_TOP = HEADER_H + 3;
const CONTENT_BOTTOM = PAGE_H - FOOTER_H - 2;
const CAPTURE_SCALE = 2;

export interface SbarAssessmentForPdf {
  assessment_id?: string | null;
  content?: string | null;
  situation?: string | null;
  background?: string | null;
  assessment?: string | null;
  recommendation?: string | null;
}

export interface SbarPdfMeta {
  assessmentId: string;
  generatedAt?: string;
}

/** Compose canonical SBAR markdown from an assessment API payload. */
export function composeSbarMarkdownFromAssessment(
  assessment: SbarAssessmentForPdf,
): string {
  if (assessment.content && assessment.content.trim()) {
    return assessment.content.trim();
  }
  return [
    "# SBAR",
    "",
    "## Situation",
    "",
    assessment.situation?.trim() || "_Not generated._",
    "",
    "## Background",
    "",
    assessment.background?.trim() || "_Not generated._",
    "",
    "## Assessment",
    "",
    assessment.assessment?.trim() || "_Not generated._",
    "",
    "## Recommendation",
    "",
    assessment.recommendation?.trim() || "_Not generated._",
  ].join("\n");
}

function drawLogo(doc: jsPDF, x: number, y: number, r: number) {
  doc.setFillColor(PRIMARY);
  doc.circle(x, y, r, "F");
  doc.setTextColor(WHITE);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(r * 3.2);
  doc.text("LEO", x, y + r * 1.1, { align: "center", baseline: "bottom" });
}

function drawHeader(doc: jsPDF, meta: SbarPdfMeta, generatedAt: string) {
  doc.setFillColor(PRIMARY);
  doc.rect(0, 0, PAGE_W, HEADER_H, "F");
  drawLogo(doc, MARGIN + 1, HEADER_H / 2, 3.8);
  doc.setTextColor(WHITE);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text("SBAR summary", MARGIN + 8, HEADER_H / 2 - 1.5, {
    baseline: "middle",
  });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7);
  doc.text(`Assessment ${meta.assessmentId}`, MARGIN + 8, HEADER_H / 2 + 2.5, {
    baseline: "middle",
  });
  doc.text(generatedAt, PAGE_W - MARGIN, HEADER_H / 2 - 1.5, {
    align: "right",
    baseline: "middle",
  });
  doc.text("AI-generated - clinician review required", PAGE_W - MARGIN, HEADER_H / 2 + 2.5, {
    align: "right",
    baseline: "middle",
  });
}

function drawFooter(doc: jsPDF, pageNum: number, pageCount: number) {
  doc.setDrawColor("#E2E8F0");
  doc.setLineWidth(0.2);
  doc.line(MARGIN, PAGE_H - FOOTER_H, PAGE_W - MARGIN, PAGE_H - FOOTER_H);
  doc.setTextColor(GREY_TEXT);
  doc.setFont("helvetica", "italic");
  doc.setFontSize(7);
  doc.text(SBAR_PDF_IG_FOOTER, PAGE_W / 2, PAGE_H - FOOTER_H + 4, {
    align: "center",
    baseline: "middle",
  });
  doc.setFont("helvetica", "normal");
  doc.text(`Page ${pageNum} of ${pageCount}`, PAGE_W - MARGIN, PAGE_H - FOOTER_H + 4, {
    align: "right",
    baseline: "middle",
  });
}

function sliceToPage(
  source: HTMLCanvasElement,
  topPx: number,
  heightPx: number,
): string {
  const slice = document.createElement("canvas");
  slice.width = source.width;
  slice.height = Math.max(1, Math.ceil(heightPx));
  const ctx = slice.getContext("2d");
  if (ctx) {
    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, slice.width, slice.height);
    ctx.drawImage(
      source,
      0,
      topPx,
      source.width,
      heightPx,
      0,
      0,
      source.width,
      heightPx,
    );
  }
  return slice.toDataURL("image/png");
}

function mountCaptureRoot(markdown: string): HTMLElement {
  const root = buildSbarPdfCaptureRoot(markdown);
  root.style.position = "fixed";
  root.style.left = "-10000px";
  root.style.top = "0";
  root.style.zIndex = "-1";
  document.body.appendChild(root);
  return root;
}

function writePages(
  doc: jsPDF,
  canvas: HTMLCanvasElement,
  slices: PdfPageSlice[],
  meta: SbarPdfMeta,
  generatedAt: string,
) {
  const contentWmm = PAGE_W - MARGIN * 2;
  const pxPerMm = canvas.width / contentWmm;
  const totalPages = slices.length;

  slices.forEach((slice, index) => {
    if (index > 0) doc.addPage();
    drawHeader(doc, meta, generatedAt);
    drawFooter(doc, index + 1, totalPages);
    const sliceData = sliceToPage(canvas, slice.topPx, slice.heightPx);
    const sliceHmm = slice.heightPx / pxPerMm;
    doc.addImage(sliceData, "PNG", MARGIN, CONTENT_TOP, contentWmm, sliceHmm);
  });
}

/**
 * Generate and download a widget-faithful SBAR PDF.
 */
export async function exportSbarPdf(
  markdown: string,
  meta: SbarPdfMeta,
): Promise<void> {
  const generatedAt =
    meta.generatedAt ||
    new Date().toLocaleString("en-GB", {
      day: "2-digit",
      month: "short",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });

  const root = mountCaptureRoot(markdown);
  try {
    await new Promise<void>((resolve) => {
      requestAnimationFrame(() => resolve());
    });

    const canvas = await html2canvas(root, {
      scale: CAPTURE_SCALE,
      backgroundColor: "#ffffff",
      useCORS: true,
      logging: false,
      windowWidth: root.scrollWidth,
    });

    const contentWmm = PAGE_W - MARGIN * 2;
    const usableHmm = CONTENT_BOTTOM - CONTENT_TOP;
    const pxPerMm = canvas.width / contentWmm;
    const pageHpx = Math.floor(usableHmm * pxPerMm);
    const scale = canvas.width / Math.max(1, root.offsetWidth);
    const blocks = collectPdfBlocks(root, scale);
    const slices = planPdfPageSlices(blocks, pageHpx, canvas.height);

    const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
    doc.setProperties({
      title: `SBAR summary - ${meta.assessmentId}`,
      subject: "LEO SBAR clinical decision support summary",
      author: "LEO by Mizaic",
      creator: "LEO by Mizaic",
    });

    writePages(doc, canvas, slices, meta, generatedAt);

    const dateSlug = new Date().toISOString().slice(0, 10);
    const idSlug = meta.assessmentId
      .replace(/[^a-zA-Z0-9_-]+/g, "-")
      .slice(0, 40);
    doc.save(`sbar-${idSlug}-${dateSlug}.pdf`);
  } finally {
    root.remove();
  }
}
