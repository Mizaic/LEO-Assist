@dataclass(frozen=True)
class GateVerdict:
    """Outcome of the hard-cut shadow-run gate evaluation."""

    passed: bool
    rationale: str
    metrics: dict[str, float]


def evaluate_shadow_gate(
    report_path: Path,
    *,
    max_age_days: int = 14,
    min_agreement: float = 1.0,
    min_recall: float = 1.0,
    now: datetime | None = None,
) -> GateVerdict:
    """Verify the shadow-run report meets the hard-cut criteria.

    The defaults are deliberately strict because the cut deletes
    code with no easy revert. The report file is generated by
    scripts/episode_v2/shadow_comparison_report.py.
    """
    if not report_path.exists():
        return GateVerdict(False, "shadow report file not found", {})
    try:
        payload = json.loads(report_path.read_text(encoding="utf-8"))
    except (ValueError, OSError) as exc:
        return GateVerdict(False, f"shadow report unreadable: {exc}", {})
    metrics = {
        "auto_case_agreement_rate": float(
            payload.get("auto_case_agreement_rate", 0.0)
        ),
        "regression_recall": float(payload.get("regression_recall", 0.0)),
        "patients_evaluated": float(payload.get("patients_evaluated", 0.0)),
    }
    when = now or datetime.now(timezone.utc)
    mtime = datetime.fromtimestamp(report_path.stat().st_mtime, tz=timezone.utc)
    if when - mtime > timedelta(days=max_age_days):
        return GateVerdict(
            False,
            f"shadow report is stale (age > {max_age_days} days)",
            metrics,
        )
    if metrics["patients_evaluated"] < 10:
        return GateVerdict(
            False,
            "shadow window did not cover at least 10 patients",
            metrics,
        )
    if metrics["auto_case_agreement_rate"] < min_agreement:
        return GateVerdict(
            False,
            (
                f"auto-case agreement rate "
                f"{metrics['auto_case_agreement_rate']:.2%} < required "
                f"{min_agreement:.2%}"
            ),
            metrics,
        )
    if metrics["regression_recall"] < min_recall:
        return GateVerdict(
            False,
            (
                f"regression recall {metrics['regression_recall']:.2%} < "
                f"required {min_recall:.2%}"
            ),
            metrics,
        )
    return GateVerdict(True, "all hard-cut gates passed", metrics)


def planned_deletions(
    repo_root: Path = REPO_ROOT,
    paths: Iterable[str] = V1_PATHS,
) -> list[Path]:
    """Resolve the list of paths that the cut will delete."""
    out: list[Path] = []
    for rel in paths:
        candidate = repo_root / rel
        if candidate.exists():
            out.append(candidate)
    return out


def perform_cut(
    repo_root: Path = REPO_ROOT,
    paths: Iterable[str] = V1_PATHS,
) -> list[Path]:
    """Delete v1 paths. Returns the list of deletions actually made."""
    deleted: list[Path] = []
    for rel in paths:
        candidate = repo_root / rel
        if not candidate.exists():
            continue
        if candidate.is_dir():
            shutil.rmtree(candidate)
        else:
            candidate.unlink()
        deleted.append(candidate)
    return deleted


def render_atlas_obsolescence_plan() -> str:
    """Print the dcId list and rationale for the manual Atlas update."""
    lines: list[str] = []
    lines.append("# Atlas obsolescence plan")
    lines.append("")
    lines.append(
        "Run the following via the user-atlas-design-controls MCP server "
        "to mark the v1 design controls Obsolete with rationale "
        "'Replaced by Episode Detector v2 + episode-aware coding + "
        "per-episode SBAR. See compliance/episode-v2-shadow-report.md "
        "for the gating evidence.'"
    )
    lines.append("")
    lines.append("## Design Outputs")
    for dc_id in RETIRE_DOS:
        lines.append(
            f"- update_design_output(dc_id='{dc_id}', status='Obsolete', ...)"
        )
    lines.append("")
    lines.append("## Design Inputs")
    for dc_id in RETIRE_DIS:
        lines.append(
            f"- update_design_input(dc_id='{dc_id}', status='Obsolete', ...)"
        )
    return "\n".join(lines) + "\n"


def _cli_main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--report",
        type=Path,
        default=REPO_ROOT / "compliance" / "episode-v2-shadow-report.json",
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Actually perform the cut. Without this, dry-run only.",
    )
    args = parser.parse_args(argv)

    verdict = evaluate_shadow_gate(args.report)
    sys.stdout.write(f"Shadow-gate verdict: {verdict.passed}\n")
    sys.stdout.write(f"Rationale: {verdict.rationale}\n")
    sys.stdout.write(f"Metrics: {json.dumps(verdict.metrics, indent=2)}\n")
    sys.stdout.write("\n")

    sys.stdout.write("Paths planned for deletion:\n")
    for path in planned_deletions():
        sys.stdout.write(f"  - {path.relative_to(REPO_ROOT)}\n")
    sys.stdout.write("\n")
    sys.stdout.write(render_atlas_obsolescence_plan())

    if not args.execute:
        sys.stdout.write("\nDry-run only. Re-run with --execute when ready.\n")
        return 0

    if not verdict.passed:
        sys.stdout.write(
            "\nABORT: shadow gate failed. Run the shadow window to "
            "completion before retrying with --execute.\n"
        )
        return 2

    deleted = perform_cut()
    sys.stdout.write(f"\nDeleted {len(deleted)} paths:\n")
    for path in deleted:
        sys.stdout.write(f"  - {path.relative_to(REPO_ROOT)}\n")
    sys.stdout.write(
        "\nNext steps: (a) run the Atlas obsolescence calls above, "
        "(b) flip the episode_pipeline flag default to 'v2', "
        "(c) remove the feature-flag plumbing in a follow-up commit.\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(_cli_main())
