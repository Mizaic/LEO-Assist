/**
 * exportContextRulesPdf
 *
 * Generates a paginated A4-landscape PDF of the context rules table.
 * Every page carries a branded header (LEO logo, title, filter, date, org)
 * and a footer (page X of Y, confidentiality notice).
 * Table column headers repeat automatically on each page via jspdf-autotable.
 *
 * Atlas trace:
 *   DO: DO-CD075278
 *   DI: DI-B5EEBC4C
 *   Look up via: get_design_control(dc_type="design-output", dc_id="DO-CD075278")
 */
import jsPDF from "jspdf";
import autoTable, { type CellHookData, type HookData } from "jspdf-autotable";

// -- Theme colours (matches services/ui/src/theme.ts) -----------------------
const PRIMARY   = "#0d46d6";
const NAVY      = "#00093b";
const LIGHT_BG  = "#F0F4FF";
const GREY_TEXT = "#596577";
const WHITE     = "#FFFFFF";

// -- Page geometry (A4 landscape, mm) ---------------------------------------
const PAGE_W  = 297;
const MARGIN  = 18;
const HEADER_H = 16;   // header band height
const FOOTER_H = 10;   // footer band height
const TABLE_START_Y = HEADER_H + 4;

// -- Friendly labels (mirrors page.tsx) -------------------------------------
const CATEGORY_LABEL: Record<string, string> = {
  NEGATED_EXISTENCE:  "Not present",
  POSSIBLE_EXISTENCE: "Possibly present",
  HISTORICAL:         "Historical",
  HYPOTHETICAL:       "Planned / pending",
  FAMILY:             "Family member",
  DECLINED:           "Patient declined",
  CANCELLED:          "Appointment missed",
};

// -- Types ------------------------------------------------------------------
export interface ContextRuleForExport {
  rule_id:     string | null;
  literal:     string;
  category:    string;
  direction:   string;
  max_scope:   number;
  description: string;
  example:     string;
  created_by:  string;
  active:      boolean;
  source:      "builtin" | "custom";
  org_id:      string | null;
}

export type FilterView = "all" | "builtin" | "custom";

// -- Per-page header --------------------------------------------------------
function drawHeader(
  doc: jsPDF,
  filter: FilterView,
  generatedAt: string,
  orgName: string,
  pageNumber: number,
  pageCount: number,
) {
  const w = doc.internal.pageSize.getWidth();

  doc.setFillColor(NAVY);
  doc.rect(0, 0, w, HEADER_H, "F");

  doc.setTextColor(WHITE);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text("LEO by Mizaic", MARGIN, HEADER_H / 2 - 2.2, { baseline: "middle" });
  doc.setFontSize(11);
  doc.text("Context Rules", MARGIN, HEADER_H / 2 + 2.4, { baseline: "middle" });

  // sub-title (filter label)
  const filterLabel: Record<FilterView, string> = {
    all:     "All rules",
    builtin: "Built-in rules",
    custom:  "Custom rules",
  };
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text(filterLabel[filter], MARGIN + 42, HEADER_H / 2 + 2.4, { baseline: "middle" });

  // right-hand meta block
  doc.setFontSize(7.5);
  const rightX = w - MARGIN;
  doc.text(`Generated: ${generatedAt}`, rightX, HEADER_H / 2 - 2.5, { align: "right", baseline: "middle" });
  if (orgName) {
    doc.text(`Organisation: ${orgName}`, rightX, HEADER_H / 2 + 1.5, { align: "right", baseline: "middle" });
  }
  doc.text(`Page ${pageNumber} of ${pageCount}`, rightX, HEADER_H / 2 + 5.5, { align: "right", baseline: "middle" });
}

// -- Per-page footer --------------------------------------------------------
function drawFooter(doc: jsPDF) {
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();

  doc.setDrawColor("#E2E8F0");
  doc.setLineWidth(0.2);
  doc.line(MARGIN, h - FOOTER_H, w - MARGIN, h - FOOTER_H);

  doc.setTextColor(GREY_TEXT);
  doc.setFont("helvetica", "italic");
  doc.setFontSize(7);
  doc.text(
    "Generated by LEO by Mizaic  ·  Contains NHS clinical configuration data  ·  Handle in accordance with your organisation's information governance policy",
    w / 2,
    h - FOOTER_H + 4,
    { align: "center", baseline: "middle" },
  );
}

// -- Column glossary ---------------------------------------------------------
const COLUMN_GUIDE: Array<{ col: string; def: string }> = [
  { col: "Phrase",               def: "The exact word or phrase LEO looks for in the clinical note." },
  { col: "Category",            def: "What the phrase signals — e.g. 'Patient declined' means the condition should not be coded as having happened." },
  { col: "Direction",           def: "Which direction from the phrase the rule applies to. FORWARD: phrase comes first — e.g. 'declined colonoscopy' (the condition follows). BACKWARD: condition comes first — e.g. 'colonoscopy was declined' (the phrase follows). BIDIRECTIONAL: works either way — e.g. 'mum had diabetes' or 'diabetes (mum)'." },
  { col: "Source",              def: "Built-in rules ship with LEO (read-only). Custom rules are added by your organisation's admins." },
  { col: "Status",              def: "Active rules run in the pipeline. Inactive rules are kept for reference only." },
  { col: "Description & Example", def: "Plain-English explanation and a concrete example of the rule in use." },
];

// -- Intro text on page 1 ---------------------------------------------------
function drawIntro(doc: jsPDF): number {
  const w = doc.internal.pageSize.getWidth();
  const usableW = w - MARGIN * 2;

  // Intro paragraph — written at a reading age of 11
  const introText =
    "Context rules are a key part of the NLP (Natural Language Processing) system that makes sure " +
    "clinical notes are read correctly. Doctors often use short phrases like 'nil', 'declined', or " +
    "'awaiting'. Without these rules the system might record something as having happened when it " +
    "did not — for example, coding a colonoscopy the patient actually refused. Context rules stop " +
    "that from happening by checking the words around each condition and working out whether it is " +
    "confirmed, planned, declined, historical, or about a family member. This report lists every " +
    "rule in use so it can be reviewed for transparency and audit.";

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(GREY_TEXT);

  const introWrapped = doc.splitTextToSize(introText, usableW);
  let y = TABLE_START_Y + 2;
  doc.text(introWrapped, MARGIN, y);
  y += introWrapped.length * 4.5 + 3;

  // Column guide heading
  doc.setFont("helvetica", "bold");
  doc.setFontSize(7.5);
  doc.setTextColor("#0F172A");
  doc.text("Column guide", MARGIN, y);
  y += 4;

  // Guide rows
  const colW = 44;
  const defW = usableW - colW - 4;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);

  for (const { col, def } of COLUMN_GUIDE) {
    const defLines = doc.splitTextToSize(def, defW);
    const rowH = defLines.length * 3.6;

    doc.setTextColor(PRIMARY);
    doc.setFont("helvetica", "bold");
    doc.text(col, MARGIN, y + 3, { baseline: "middle" });

    doc.setTextColor(GREY_TEXT);
    doc.setFont("helvetica", "normal");
    doc.text(defLines, MARGIN + colW, y, { baseline: "top" });

    y += rowH + 1.5;
  }

  // Divider before table
  doc.setDrawColor("#E2E8F0");
  doc.setLineWidth(0.2);
  doc.line(MARGIN, y + 1, w - MARGIN, y + 1);

  return y + 4;
}

// -- Main export function ---------------------------------------------------
export function exportContextRulesPdf(
  rules: ContextRuleForExport[],
  filter: FilterView,
  orgName = "",
): void {
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });

  const generatedAt = new Date().toLocaleString("en-GB", {
    day: "2-digit", month: "short", year: "numeric",
    hour: "2-digit", minute: "2-digit",
  });

  const filterLabel: Record<FilterView, string> = {
    all:     "All Context Rules",
    builtin: "Built-in Context Rules",
    custom:  "Custom Context Rules",
  };

  doc.setProperties({
    title:    filterLabel[filter],
    subject:  "LEO NLP context rule configuration",
    author:   orgName || "LEO by Mizaic",
    creator:  "LEO by Mizaic",
    keywords: "context rules, NLP, clinical coding, LEO",
  });

  // Replace Unicode arrows that Courier cannot render
  const sanitize = (s: string) => s.replace(/→/g, "->").replace(/←/g, "<-");

  // Rows
  const bodyRows = rules.map((r) => {
    const categoryLabel = CATEGORY_LABEL[r.category] ?? r.category;
    const descCell = [r.description, r.example ? `e.g. ${sanitize(r.example)}` : ""]
      .filter(Boolean)
      .join("\n");

    return {
      literal:   r.literal,
      category:  categoryLabel,
      direction: r.direction,
      source:    r.source === "builtin" ? "Built-in" : "Custom",
      status:    r.active ? "Active" : "Inactive",
      desc:      descCell,
      _source:   r.source,
      _active:   r.active,
    };
  });

  // Total pages are unknown during generation — we draw headers with a placeholder
  // count and overwrite the page-number text in a second pass once the total is known.

  const tableConfig = (introEndY: number) => ({
    startY: introEndY,
    // top margin controls where the table resumes on pages 2+
    margin: { top: TABLE_START_Y, left: MARGIN, right: MARGIN, bottom: FOOTER_H + 2 },
    showHead: "everyPage" as const,
    theme: "striped" as const,
    tableWidth: "auto" as const,
    columns: [
      { header: "Phrase",           dataKey: "literal"   },
      { header: "Category",         dataKey: "category"  },
      { header: "Direction",        dataKey: "direction" },
      { header: "Source",           dataKey: "source"    },
      { header: "Status",           dataKey: "status"    },
      { header: "Description & Example", dataKey: "desc" },
    ],
    columnStyles: {
      literal:   { cellWidth: 42, font: "courier", fontSize: 7.5 },
      category:  { cellWidth: 38 },
      direction: { cellWidth: 28 },  // 28 fits "BIDIRECTIONAL" on one line
      source:    { cellWidth: 20 },
      status:    { cellWidth: 18 },
      desc:      { cellWidth: 115 }, // reduced by 6 to keep total at 261mm
    },
    headStyles: {
      fillColor:  PRIMARY as unknown as [number, number, number],
      textColor:  WHITE,
      fontStyle:  "bold" as const,
      fontSize:   8,
      cellPadding: 2.5,
    },
    bodyStyles: {
      fontSize:    8,
      cellPadding: 2.5,
      overflow:    "linebreak" as const,
      valign:      "top" as const,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252] as unknown as [number, number, number],
    },
    willDrawCell: (data: CellHookData) => {
      const row = bodyRows[data.row.index];
      if (!row) return;

      // Shade built-in rows
      if (row._source === "builtin") {
        data.cell.styles.fillColor = LIGHT_BG as unknown as [number, number, number];
      }
      // Dim inactive rows
      if (!row._active) {
        data.cell.styles.textColor = "#AAAAAA";
      }
      // Italic for the example line inside the desc cell
      if (data.column.dataKey === "desc" && typeof data.cell.text !== "string") {
        // jspdf-autotable splits on \n; we can't easily style sub-lines here,
        // but the "e.g." prefix makes it clear visually.
      }
    },
    didDrawPage: (data: HookData) => {
      const pageNum = (doc as jsPDF & { internal: { getCurrentPageInfo(): { pageNumber: number } } })
        .internal.getCurrentPageInfo().pageNumber;
      // Draw header with placeholder page count (will be patched below)
      drawHeader(doc, filter, generatedAt, orgName, pageNum, 9999);
      drawFooter(doc);
    },
  });

  // -- Page 1: draw intro then table
  const introEndY = drawIntro(doc);
  autoTable(doc, {
    body: bodyRows.map((r) => [r.literal, r.category, r.direction, r.source, r.status, r.desc]),
    ...(tableConfig(introEndY) as object),
  });

  const totalPages = doc.getNumberOfPages();

  // -- Patch all page headers with correct total page count
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    // Overwrite the right-hand meta area with correct count
    const w = PAGE_W;

    // White-out the old page count text area (small rectangle)
    doc.setFillColor(PRIMARY);
    doc.rect(w - MARGIN - 55, HEADER_H / 2 + 3, 55, 4.5, "F");

    // Re-draw with correct total
    doc.setTextColor(WHITE);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.text(`Page ${p} of ${totalPages}`, w - MARGIN, HEADER_H / 2 + 5.5, {
      align: "right",
      baseline: "middle",
    });
  }

  const dateSlug = new Date().toISOString().slice(0, 10);
  const filterSlug = filter === "all" ? "all" : filter;
  doc.save(`context-rules-${filterSlug}-${dateSlug}.pdf`);
}
